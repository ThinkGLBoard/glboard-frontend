"use client";

import type { Metadata } from "next";
import { Geist_Mono, Poppins } from "next/font/google";
import "./globals.css";
import { NavigationMenu } from "@radix-ui/react-navigation-menu";
import { AlertDialogHeader, AlertDialogFooter } from "@/ui/alert-dialog";
import { AlertDialog, AlertDialogContent, AlertDialogTitle, AlertDialogDescription, AlertDialogCancel, AlertDialogAction } from "@radix-ui/react-alert-dialog";
import { AppFooter } from "@/components/AppFooter";
import { ReactNode, useEffect, useState } from "react";
import { SharedHeader } from "@/components/SharedHeader";
import { usePathname, useRouter } from "next/navigation";

const poppins = Poppins({
  variable: "--font-poppins",
  subsets: ["latin"],
  weight: ["300", "400", "500", "600", "700"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

const metadata: Metadata = {
  title: "GLBoard",
  description: "Generated by create next app",
};

interface AppLayoutProps {
  children: ReactNode;
  currentPage?: string;
  onNavigate?: (page: string) => void;
  onLogout?: () => void;
  isLoggedIn?: boolean;
  onLogin?: () => void;
  onSignup?: () => void;
  user?: { name: string; email: string };
}

export default function AppLayout({
  children,
  currentPage = "landing",
  onNavigate = () => {},
  onLogout = () => {},
  isLoggedIn: initialIsLoggedIn = false,
  onLogin,
  onSignup,
  user: initialUser,
}: AppLayoutProps) {
  const pathname = usePathname();
  const router = useRouter();
  const [logoutDialogOpen, setLogoutDialogOpen] = useState(false);
  const [mobileMenuOpen, setMobileMenuOpen] = useState(false);
  const [isSidebarExpanded, setIsSidebarExpanded] = useState(false);
  const [authSession, setAuthSession] = useState({
    isLoggedIn: initialIsLoggedIn,
    user: initialUser,
  });

  useEffect(() => {
    const syncAuthSession = () => {
      const token = sessionStorage.getItem("glboard_auth_token");
      const name = sessionStorage.getItem("glboard_auth_user_name");
      setAuthSession({
        isLoggedIn: Boolean(token),
        user: token ? { name: name || "Usuário", email: "" } : undefined,
      });
    };

    syncAuthSession();
    window.addEventListener("glboard-auth-changed", syncAuthSession);
    return () =>
      window.removeEventListener("glboard-auth-changed", syncAuthSession);
  }, []);

  const isLoggedIn = authSession.isLoggedIn;
  const user = authSession.user;

  const handleLogoutClick = () => {
    setLogoutDialogOpen(true);
  };

  const confirmLogout = () => {
    setLogoutDialogOpen(false);
    sessionStorage.removeItem("glboard_auth_token");
    sessionStorage.removeItem("glboard_auth_user_name");
    setAuthSession({ isLoggedIn: false, user: undefined });
    window.dispatchEvent(new Event("glboard-auth-changed"));
    onLogout();
  };

  const isLandingPage = currentPage === 'landing';
  const isAuthenticationPage =
    pathname === "/login" || pathname === "/signup";
  const isAboutPage = currentPage === 'about';
  const isManualPage = currentPage === 'manual';
  const isDocumentationsPage = currentPage === 'documentations';

  const scrollToSection = (id: string) => {
    const element = document.getElementById(id);
    element?.scrollIntoView({ behavior: 'smooth' });
    setMobileMenuOpen(false);
  };


 return (
  <html lang="pt-BR">
    <body>
    <div className="min-h-screen bg-background flex flex-col">
      {/* Public Pages Navbar (SharedHeader) */}
      {!isAuthenticationPage && !isLoggedIn && (
        <SharedHeader 
          onLogin={onLogin || (() => router.push("/login"))}
          onNavigate={onNavigate}
          isLoggedIn={isLoggedIn}
          currentPage={currentPage}
        />
      )}

      {/* Logged-in Pages Navbar */}
      {!isAuthenticationPage && isLoggedIn && (
        <SharedHeader 
          onLogin={() => {}} 
          onNavigate={onNavigate}
          isLoggedIn={isLoggedIn}
          userName={user?.name.split(' ')[0] || 'Usuário'}
          currentPage={currentPage}
        />
      )}

      {/* Main Content */}
      <main className="flex-1">{children}</main>

      {/* Footer */}
      {!isAuthenticationPage && <AppFooter />}

      {/* Logout Confirmation Dialog */}
      <AlertDialog open={logoutDialogOpen} onOpenChange={setLogoutDialogOpen}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Deseja realmente sair do GLBoard?</AlertDialogTitle>
            <AlertDialogDescription>
              Você será redirecionado para a página inicial e precisará fazer login novamente para acessar seus jogos.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel>Cancelar</AlertDialogCancel>
            <AlertDialogAction onClick={confirmLogout} className="bg-destructive text-destructive-foreground hover:bg-destructive/90">
              Sim, sair
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </div>
    </body>
    </html>
  );
}

